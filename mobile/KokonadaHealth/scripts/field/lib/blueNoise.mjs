// The field's static blue-noise tile (field.dither.pattern "blueNoise64.static"), made in-house by
// void-and-cluster (R. Ulichney, "The void-and-cluster method for dither array generation", 1993),
// so there is no licence question. Pure and deterministic: a seeded generator, a toroidal Gaussian
// energy, and ties broken by the lowest index.
//
// Two channels from two seeds: R holds the dither (±1/255 on OKLab L), G the grain. Each channel is
// a permutation of the 4096 ranks, stored as 256 levels (rank >> 4), 16 pixels per level, so the
// centred value 2·(level + 0.5)/256 − 1 has a mean of exactly zero over the tile.

export const BLUE_NOISE_SPEC = { size: 64, sigma: 1.5, seeds: { dither: 1, grain: 2 } };

/** A 32-bit linear congruential generator (Numerical Recipes), as floats in [0, 1). */
function lcg(seed) {
  let state = seed >>> 0;
  return () => {
    state = (Math.imul(state, 1664525) + 1013904223) >>> 0;
    return state / 4294967296;
  };
}

/** The rank (0..size²−1) of every pixel, row by row. */
export function voidAndCluster(size, seed, sigma) {
  const n = size * size;
  const reach = Math.min(Math.floor(size / 2), Math.ceil(4 * sigma));
  const kernel = [];
  for (let dy = -reach; dy <= reach; dy++) {
    for (let dx = -reach; dx <= reach; dx++) {
      kernel.push([dx, dy, Math.exp(-(dx * dx + dy * dy) / (2 * sigma * sigma))]);
    }
  }
  const wrap = (v) => ((v % size) + size) % size;
  const energy = new Float64Array(n);
  const ones = new Uint8Array(n);
  const add = (i, sign) => {
    const x = i % size;
    const y = (i - x) / size;
    for (const [dx, dy, w] of kernel) {
      energy[wrap(y + dy) * size + wrap(x + dx)] += sign * w;
    }
  };
  const set = (i, on) => {
    if (ones[i] === on) return;
    ones[i] = on;
    add(i, on ? 1 : -1);
  };
  const tightestCluster = () => {
    let best = -1;
    for (let i = 0; i < n; i++) if (ones[i] && (best < 0 || energy[i] > energy[best])) best = i;
    return best;
  };
  const largestVoid = () => {
    let best = -1;
    for (let i = 0; i < n; i++) if (!ones[i] && (best < 0 || energy[i] < energy[best])) best = i;
    return best;
  };

  // The prototype: about a tenth of the pixels, then swapped until no swap moves a pixel.
  const random = lcg(seed);
  const initial = Math.max(1, Math.floor(n / 10));
  let placed = 0;
  while (placed < initial) {
    const i = Math.floor(random() * n);
    if (!ones[i]) {
      set(i, 1);
      placed++;
    }
  }
  for (let guard = 0; guard < n * 4; guard++) {
    const cluster = tightestCluster();
    set(cluster, 0);
    const vacancy = largestVoid();
    if (vacancy === cluster) {
      set(cluster, 1);
      break;
    }
    set(vacancy, 1);
  }
  const prototype = Uint8Array.from(ones);
  const prototypeEnergy = Float64Array.from(energy);
  const rank = new Int32Array(n).fill(-1);

  // Phase 1: take the prototype's pixels away from the tightest cluster, ranking them downwards.
  for (let r = initial - 1; r >= 0; r--) {
    const i = tightestCluster();
    set(i, 0);
    rank[i] = r;
  }
  // Phases 2 and 3: from the prototype, fill the largest void until every pixel has a rank.
  ones.set(prototype);
  energy.set(prototypeEnergy);
  for (let r = initial; r < n; r++) {
    const i = largestVoid();
    set(i, 1);
    rank[i] = r;
  }
  return rank;
}

const hexOf = (levels) => Array.from(levels, (v) => v.toString(16).padStart(2, '0')).join('');

/** The generated TypeScript module, byte for byte. */
export function blueNoiseModule() {
  const { size, sigma, seeds } = BLUE_NOISE_SPEC;
  const levels = (seed) => Array.from(voidAndCluster(size, seed, sigma), (r) => r >> 4);
  const dither = hexOf(levels(seeds.dither));
  const grain = hexOf(levels(seeds.grain));
  const chunk = (hex) => hex.match(/.{1,128}/g).map((line) => `    '${line}'`).join(',\n');
  return [
    '// GENERATED by scripts/field/blueNoise.mjs: do not edit. A 64×64 void-and-cluster tile per channel,',
    '// each a permutation of 4096 ranks stored as 256 levels (rank >> 4), two hex digits per pixel, row by row.',
    '',
    'export const BLUE_NOISE = {',
    `  size: ${size},`,
    `  sigma: ${sigma},`,
    `  seeds: { dither: ${seeds.dither}, grain: ${seeds.grain} },`,
    '  dither: [',
    `${chunk(dither)},`,
    "  ].join(''),",
    '  grain: [',
    `${chunk(grain)},`,
    "  ].join(''),",
    '} as const;',
    '',
  ].join('\n');
}
