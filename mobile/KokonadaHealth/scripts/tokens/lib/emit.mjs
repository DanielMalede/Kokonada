// The token generator: no dependencies, one output contract.
//
// buildTokenModel turns the sources into plain values: dimensions in dp, durations in ms, every
// colour as { hex, alpha, oklch, oklab }, aliases resolved, and the $extensions data kept by path
// (without locks or hex markers). renderModule writes that model as TypeScript, byte for byte the
// same for the same sources. Full F1 swaps this for Style Dictionary under a byte-identical test.

import { oklchToOklab } from '../../../src/design/v2/color/oklab.ts';
import { ALIAS, flatten, isToken, resolveAlias, validateSources } from './schema.mjs';
import { BASE_FILE, DIRECTION_FILE, sha256 } from './sources.mjs';

const OUTPUT_HEADER = [
  '// GENERATED by scripts/tokens/generate.mjs from design-tokens/*.tokens.json. Do not edit.',
  '// Regenerate: node scripts/tokens/generate.mjs. The freshness test fails when this file and its',
  '// sources disagree; TOKENS_SOURCE holds the sha256 of each source file it was built from.',
];

const isObject = (v) => v !== null && typeof v === 'object' && !Array.isArray(v);
const byName = (a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0);

/** Ten decimals: stable across platforms' last-bit differences, far below any visible step. */
function round(x) {
  const r = Number(x.toFixed(10));
  return r === 0 ? 0 : r;
}

function colour(value) {
  const [L, C, h] = value.components;
  const lab = oklchToOklab({ L, C, h });
  return { hex: value.hex, alpha: value.alpha, oklch: [L, C, h], oklab: [round(lab.L), round(lab.a), round(lab.b)] };
}

function valueOf(tokens, path) {
  let token = tokens.get(path);
  if (token.$type !== 'string' && typeof token.$value === 'string' && ALIAS.test(token.$value)) {
    token = resolveAlias(tokens, path).token;
  }
  const value = token.$value;
  switch (token.$type) {
    case 'color':
      return colour(value);
    case 'dimension':
    case 'duration':
      return value.value;
    case 'shadow':
      return value.map((layer) => ({
        color: colour(layer.color),
        offsetX: layer.offsetX.value,
        offsetY: layer.offsetY.value,
        blur: layer.blur.value,
        spread: layer.spread.value,
        inset: layer.inset,
      }));
    case 'cubicBezier':
      return [...value];
    default:
      return value;
  }
}

function valueTree(node, prefix, tokens, shadowPaths) {
  const out = {};
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith('$')) {
      continue;
    }
    const path = prefix ? `${prefix}.${key}` : key;
    if (isToken(child)) {
      out[key] = valueOf(tokens, path);
      if (tokens.get(path).$type === 'shadow') {
        shadowPaths.add(path);
      }
    } else if (isObject(child)) {
      const sub = valueTree(child, path, tokens, shadowPaths);
      if (Object.keys(sub).length > 0) {
        out[key] = sub;
      }
    }
  }
  return out;
}

const ROOT = '$root';

function extensionsOf(node, path, out = {}) {
  const ext = isObject(node.$extensions) && isObject(node.$extensions['com.kokonada']) ? node.$extensions['com.kokonada'] : {};
  const kept = Object.fromEntries(Object.entries(ext).filter(([key]) => key !== 'lock' && key !== 'hex'));
  if (Object.keys(kept).length > 0) {
    out[path || ROOT] = kept;
  }
  for (const [key, child] of Object.entries(node)) {
    if (!key.startsWith('$') && isObject(child)) {
      extensionsOf(child, path ? `${path}.${key}` : key, out);
    }
  }
  return out;
}

function analyse(sources) {
  const { errors } = validateSources(sources);
  if (errors.length > 0) {
    throw new Error(`the token sources do not pass the schema:\n${errors.join('\n')}`);
  }
  const sorted = [...sources].sort(byName);
  const tokensOf = (json) => new Map(flatten(json).filter(([, node]) => isToken(node)));
  const base = sorted.find((s) => s.name === BASE_FILE);
  const directions = sorted
    .filter((s) => DIRECTION_FILE.test(s.name))
    .map((s) => ({ id: s.name.match(DIRECTION_FILE)[1], json: s.json }));
  const shadowPaths = new Set();
  const model = {
    sources: Object.fromEntries(sorted.map((s) => [s.name, sha256(s.bytes)])),
    base: valueTree(base.json, '', tokensOf(base.json), new Set()),
    directions: Object.fromEntries(directions.map((d) => [d.id, valueTree(d.json, '', tokensOf(d.json), shadowPaths)])),
    extensions: {
      base: extensionsOf(base.json, ''),
      ...Object.fromEntries(directions.map((d) => [d.id, extensionsOf(d.json, '')])),
    },
  };
  return { model, shadowPaths };
}

/** sources: [{ name, bytes, json }] → the plain values the generated module holds. */
export function buildTokenModel(sources) {
  return analyse(sources).model;
}

// ---------------------------------------------------------------- rendering

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const quote = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n')}'`;
const key = (k) => (IDENTIFIER.test(k) ? k : quote(k));
const WIDTH = 100;

const join = (path, k) => (path ? `${path}.${k}` : k);

/** One-line TypeScript. Shadow lists carry their type, so an empty one is not inferred never[]. */
function inline(value, path, shadowPaths) {
  const suffix = shadowPaths.has(path) ? ' as ShadowLayer[]' : '';
  if (Array.isArray(value)) {
    return `[${value.map((v) => inline(v, '', shadowPaths)).join(', ')}]${suffix}`;
  }
  if (isObject(value)) {
    const entries = Object.entries(value);
    return entries.length === 0 ? '{}' : `{ ${entries.map(([k, v]) => `${key(k)}: ${inline(v, join(path, k), shadowPaths)}`).join(', ')} }`;
  }
  if (typeof value === 'string') {
    return quote(value);
  }
  return String(value);
}

/** TypeScript for `value` at `path`: on one line when it fits, otherwise one entry per line. */
function render(value, indent, path, shadowPaths) {
  const suffix = shadowPaths.has(path) ? ' as ShadowLayer[]' : '';
  const flat = inline(value, path, shadowPaths);
  if (!(Array.isArray(value) || isObject(value)) || indent.length + flat.length <= WIDTH) {
    return flat;
  }
  const inner = `${indent}  `;
  if (Array.isArray(value)) {
    return `[\n${value.map((v) => `${inner}${render(v, inner, '', shadowPaths)},`).join('\n')}\n${indent}]${suffix}`;
  }
  const lines = Object.entries(value).map(([k, v]) => `${inner}${key(k)}: ${render(v, inner, join(path, k), shadowPaths)},`);
  return `{\n${lines.join('\n')}\n${indent}}`;
}

function renderModule(model, shadowPaths) {
  const ids = Object.keys(model.directions);
  const [first, ...rest] = ids;
  const out = [
    ...OUTPUT_HEADER,
    '',
    `export const TOKENS_SOURCE = ${render(model.sources, '', '', new Set())};`,
    '',
    `export type DirectionId = ${ids.map(quote).join(' | ')};`,
    "export type Face = 'dark' | 'light';",
    '',
    'export interface ColorValue {',
    '  readonly hex: string;',
    '  readonly alpha: number;',
    '  readonly oklch: readonly number[];',
    '  readonly oklab: readonly number[];',
    '}',
    '',
    'export interface ShadowLayer {',
    '  readonly color: ColorValue;',
    '  readonly offsetX: number;',
    '  readonly offsetY: number;',
    '  readonly blur: number;',
    '  readonly spread: number;',
    '  readonly inset: boolean;',
    '}',
    '',
    `export const BASE = ${render(model.base, '', '', new Set())};`,
    '',
    `const ${first} = ${render(model.directions[first], '', '', shadowPaths)};`,
    '',
    `export type DirectionTokens = typeof ${first};`,
    '',
    ...rest.flatMap((id) => [`const ${id}: DirectionTokens = ${render(model.directions[id], '', '', shadowPaths)};`, '']),
    `export const DIRECTIONS: Readonly<Record<DirectionId, DirectionTokens>> = { ${ids.join(', ')} };`,
    '',
  ];
  return out.join('\n');
}

const EXTENSIONS_HEADER = [
  '// GENERATED by scripts/tokens/generate.mjs from design-tokens/*.tokens.json. Do not edit.',
  '// The $extensions data: hero scenes, hardest placements, graph and clock tables. Only the lab,',
  '// scripts and tests import this module (extensionsBoundary.test.ts); the app reads tokens.generated.ts.',
  '// EXTENSIONS_SOURCE holds the sha256 of each source file it was built from.',
];

function renderExtensionsModule(model) {
  return [
    ...EXTENSIONS_HEADER,
    '',
    `export const EXTENSIONS_SOURCE = ${render(model.sources, '', '', new Set())};`,
    '',
    `export const EXTENSIONS = ${render(model.extensions, '', '', new Set())};`,
    '',
  ].join('\n');
}

/** sources: [{ name, bytes, json }] → the text of tokens.generated.ts. */
export function generateTokensModule(sources) {
  const { model, shadowPaths } = analyse(sources);
  return renderModule(model, shadowPaths);
}

/** sources: [{ name, bytes, json }] → the text of tokens.extensions.generated.ts. */
export function generateExtensionsModule(sources) {
  return renderExtensionsModule(analyse(sources).model);
}
